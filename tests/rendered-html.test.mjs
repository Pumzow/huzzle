  assert.match(sceneManager, /new MainMenuScene/);
  assert.match(sceneManager, /new PuzzleScene/);
  assert.match(sceneManager, /config: customLevelSceneConfig/);
  assert.match(sceneManager, /soundManager\.playSound\(this\.soundtrack, appConfig\.soundtrack\.loop, "music"\)/);
  assert.match(introScene, /Images provided by Pexels/);
  assert.match(introScene, /appConfig\.intro\.durationMs/);
