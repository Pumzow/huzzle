  assert.match(appConfig, /file: "sounds\/huzzle-soundtrack\.wav"/);
  assert.match(appConfig, /durationMs: 1800/);
  assert.match(appConfig, /storageKey: "huzzle-sfx-muted"/);
  assert.match(appConfig, /resolveAssetPath/);
  assert.match(sceneConfig, /showMoves: true/);
