  assert.match(customLevelConfig, /controls: \{\s+enabled: true/);

  assert.match(images, /createSampleImage/);
  assert.match(images, /normalizeImage/);
  assert.match(board, /export class PuzzleBoard/);
  assert.match(board, /gameConfig\.pieces\.gap/);
  assert.match(board, /gridSize \* TILE_TEXTURE_SIZE/);
  assert.match(board, /sprite\.roundPixels = true/);
  assert.doesNotMatch(board, /const shadow = new Graphics/);
  assert.match(board, /relocateGroup/);
  assert.match(board, /recomputeConnections/);
  assert.match(board, /connectedNeighbors/);
  assert.match(board, /drawComponentOutline/);
  assert.match(board, /gameConfig\.pieces\.outlineWidth/);
  assert.doesNotMatch(board, /outline\.roundRect/);
  assert.match(board, /activeGroup\.forEach/);
  assert.match(board, /pointerdown/);
  assert.match(board, /pointermove/);
  assert.match(board, /tile\.slot === tile\.row \* gridSize \+ tile\.col/);
  assert.match(board, /coordinateFor/);
  assert.match(board, /coordinateDistance/);
  assert.match(board, /new Polygon\(tilePoints\)/);
  assert.match(board, /new Graphics\(\)\.poly\(tilePoints\)\.fill/);
  assert.match(board, /const hexImageSize = Math\.max\(gridWidth, gridHeight\)/);
  assert.match(board, /const octagonCut = tileWidth \* \(1 - Math\.SQRT1_2\)/);
  assert.match(board, /minimumSwapsToSolve/);
  assert.match(board, /onStart\(\)/);

  assert.match(scene, /export class PuzzleScene/);
  assert.match(scene, /new PuzzleBoard/);
  assert.match(scene, /new PuzzleHUD/);
  assert.match(scene, /new PuzzleControls/);
  assert.match(scene, /new TargetPreview/);
  assert.match(scene, /new CompletionModal/);
  assert.match(scene, /changeGridSize/);
  assert.match(scene, /changeTileShape/);
  assert.match(scene, /gameConfig\.scoring\.secondsPerStartingSet/);
  assert.match(scene, /this\.progress\.moves > this\.progress\.moveLimit/);
  assert.match(completion, /earnedStars === 3 \? "Excellent!" : earnedStars === 2 \? "Well done!" : "Puzzle completed!"/);
